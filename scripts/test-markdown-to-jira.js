#!/usr/bin/env node
/**
 * Test script for Markdown to Jira ADF conversion
 * 
 * Usage:
 *   node scripts/test-markdown-to-jira.js --dry-run    # Just output ADF JSON
 *   node scripts/test-markdown-to-jira.js              # Create actual Jira issue
 */

import { marked } from 'marked';
import { markdownToADF } from '../src/utils/markdown-to-adf.js';
import { JiraService } from '../src/services/jira-service.js';
import { Config } from '../src/utils/config.js';
import chalk from 'chalk';

// Sample markdown content to test
const sampleMarkdown = `## Security Vulnerabilities Report

### Summary

**Application:** Test Application  
**Total Vulnerabilities:** 15  
**Critical:** 3 | **High:** 5 | **Medium:** 4 | **Low:** 3

---

### Vulnerabilities by Type

#### SQL Injection (Critical)

**Count:** 3 occurrence(s)

- **[Critical]** src/database/query.js:45
  \`const sql = "SELECT * FROM users WHERE id = " + userId;\`
- **[Critical]** src/api/search.php:128
  \`$query = "SELECT * FROM products WHERE name LIKE '%" . $_GET['q'] . "%'";\`
- **[Critical]** backend/models/user.cs:89

**Remediation Guide:** [View Article](https://cloud.appscan.com/api/v4/Reports/Article/?issuetype=SQL.Injection)

#### Cross-Site Scripting (XSS) (High)

**Count:** 5 occurrence(s)

- **[High]** frontend/components/Comment.jsx:34
  \`<div dangerouslySetInnerHTML={{__html: userComment}} />\`
- **[High]** views/profile.ejs:67
- **[High]** public/js/display.js:123

_... and 2 more occurrence(s)_

**Remediation Guide:** [View Article](https://cloud.appscan.com/api/v4/Reports/Article/?issuetype=XSS)

### Remediation Recommendations

1. **Use parameterized queries** for all database interactions
2. **Sanitize all user inputs** before rendering
3. **Enable Content Security Policy (CSP)** headers
4. **Implement input validation** on both client and server side

#### Code Example

\`\`\`javascript
// BAD - SQL Injection vulnerable
const query = \`SELECT * FROM users WHERE id = \${userId}\`;

// GOOD - Parameterized query
const query = 'SELECT * FROM users WHERE id = ?';
db.execute(query, [userId]);
\`\`\`

### Next Steps

- [ ] Review all flagged vulnerabilities
- [ ] Implement fixes according to remediation guide
- [ ] Run security scan again to verify fixes
- [ ] Update security documentation

---

**AppScan Issue IDs:** 12345, 12346, 12347, 12348, 12349, 12350, 12351, 12352, 12353, 12354, 12355, 12356, 12357, 12358, 12359

_Generated by AppScan Client - Automated Security Scanner_
`;

async function main() {
  const isDryRun = process.argv.includes('--dry-run');

  console.log(chalk.blue('\n🔍 Markdown to Jira ADF Converter Test\n'));
  console.log(chalk.gray('Mode:'), isDryRun ? chalk.yellow('DRY RUN') : chalk.green('LIVE'));
  console.log(chalk.gray('─'.repeat(60)));

  try {
    // Step 1: Parse markdown with marked
    console.log(chalk.blue('\n📝 Parsing markdown...'));
    const tokens = marked.lexer(sampleMarkdown);
    console.log(chalk.green(`✓ Parsed ${tokens.length} top-level tokens`));

    // Step 2: Convert to ADF
    console.log(chalk.blue('\n🔄 Converting to ADF...'));
    const adf = markdownToADF(tokens);
    console.log(chalk.green(`✓ Generated ADF with ${adf.content.length} content nodes`));

    // Step 3: Output ADF JSON
    console.log(chalk.blue('\n📄 ADF Output:\n'));
    console.log(JSON.stringify(adf, null, 2));

    if (isDryRun) {
      console.log(chalk.yellow('\n✓ Dry run complete - no Jira issue created\n'));
      return;
    }

    // Step 4: Create actual Jira issue
    console.log(chalk.blue('\n🎫 Creating Jira issue...\n'));
    
    const config = new Config();
    
    if (!config.isJiraValid()) {
      console.error(chalk.red('✗ Jira is not configured'));
      console.log(chalk.yellow('\nPlease configure Jira credentials:'));
      console.log(chalk.gray('  JIRA_HOST=https://your-domain.atlassian.net'));
      console.log(chalk.gray('  JIRA_EMAIL=your-email@example.com'));
      console.log(chalk.gray('  JIRA_API_TOKEN=your-api-token'));
      console.log(chalk.gray('  JIRA_PROJECT_KEY=YOUR-PROJECT\n'));
      process.exit(1);
    }

    const projectKey = config.getJiraProjectKey();
    if (!projectKey) {
      console.error(chalk.red('✗ JIRA_PROJECT_KEY not configured\n'));
      process.exit(1);
    }

    console.log(chalk.gray('  Project:'), chalk.cyan(projectKey));
    console.log(chalk.gray('  Host:'), chalk.cyan(config.getJiraHost()));
    console.log();

    const jiraService = new JiraService(config);
    jiraService.initialize();

    const issue = await jiraService.createIssue(
      projectKey,
      '[TEST] Security Vulnerabilities Report - Markdown Conversion Test',
      sampleMarkdown, // Service will convert to ADF
      'Bug',
      {
        labels: ['appscan', 'security', 'test'],
      }
    );

    const jiraUrl = jiraService.getJiraUrl(issue.key);

    console.log(chalk.green('\n✓ Jira issue created successfully!\n'));
    console.log(chalk.gray('  Issue Key:'), chalk.cyan(issue.key));
    console.log(chalk.gray('  Issue ID:'), chalk.gray(issue.id));
    console.log(chalk.gray('  URL:'), chalk.blue(jiraUrl));
    console.log();
    console.log(chalk.yellow('  → Open in browser:'), chalk.underline.blue(jiraUrl));
    console.log();

  } catch (error) {
    console.error(chalk.red('\n✗ Error:'), error.message);
    if (error.response?.data) {
      console.error(chalk.gray('\nJira API Response:'));
      console.error(JSON.stringify(error.response.data, null, 2));
    }
    console.log();
    process.exit(1);
  }
}

main();
